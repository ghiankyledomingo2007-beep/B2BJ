def check(name, glyphs):
    for ch, rows in glyphs.items():
        widths = {len(r) for r in rows}
        assert len(widths) == 1, f"{name} {ch!r}: ragged rows {widths}"
        assert all(set(r) <= {'#', '.'} for r in rows), f"{name} {ch!r}: bad pixel"


def rects(rows, cap):
    """Each horizontal run of pixels becomes one clockwise rectangle (y up, baseline 0)."""
    out = []
    for r, row in enumerate(rows):
        top = (cap - r) * PX
        x = 0
        while x < len(row):
            if row[x] != '#':
                x += 1
                continue
            start = x
            while x < len(row) and row[x] == '#':
                x += 1
            out.append((start * PX, top - PX, x * PX, top))
    return out


def build(path, family, glyphs, alias, cap, ascent, descent, gap, spacing, space):
    from fontTools.fontBuilder import FontBuilder
    from fontTools.pens.ttGlyphPen import TTGlyphPen
    from fontTools.ttLib import newTable

    names = {}
    for ch in glyphs:
        names[ch] = f"uni{ord(ch):04X}"
    order = [".notdef", "space"] + [names[ch] for ch in glyphs]
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(order)
    cmap = {32: "space", 0xA0: "space"}
    for ch, n in names.items():
        cmap[ord(ch)] = n
        if family.endswith("Display") and ch.isalpha() and ch.isupper():
            cmap[ord(ch.lower())] = n
    for src, dst in alias.items():
        if dst in names:
            cmap[ord(src)] = names[dst]
    fb.setupCharacterMap(cmap)

    glyf, metrics = {}, {}
    pen = TTGlyphPen(None)
    pen.moveTo((PX, 0)); pen.lineTo((PX, cap * PX)); pen.lineTo((4 * PX, cap * PX)); pen.lineTo((4 * PX, 0)); pen.closePath()
    pen.moveTo((2 * PX, PX)); pen.lineTo((3 * PX, PX)); pen.lineTo((3 * PX, (cap - 1) * PX)); pen.lineTo((2 * PX, (cap - 1) * PX)); pen.closePath()
    glyf[".notdef"] = pen.glyph(); metrics[".notdef"] = (5 * PX, PX)
    glyf["space"] = TTGlyphPen(None).glyph(); metrics["space"] = (space * PX, 0)
    for ch, rows in glyphs.items():
        pen = TTGlyphPen(None)
        boxes = rects(rows, cap)
        for x0, y0, x1, y1 in boxes:
            pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
        glyf[names[ch]] = pen.glyph()
        width = len(rows[0])
        metrics[names[ch]] = ((width + spacing) * PX, min((b[0] for b in boxes), default=0))
    fb.setupGlyf(glyf)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=ascent * PX, descent=-descent * PX, lineGap=gap * PX)
    fb.setupNameTable({"familyName": family, "styleName": "Regular",
                       "uniqueFontIdentifier": family + " Regular", "fullName": family,
                       "psName": family.replace(" ", "") + "-Regular", "version": "Version 1.000",
                       "copyright": "Drawn for Blob to Blade"})
    fb.setupOS2(version=4, sTypoAscender=ascent * PX, sTypoDescender=-descent * PX, sTypoLineGap=gap * PX,
                usWinAscent=ascent * PX, usWinDescent=descent * PX, fsSelection=0x40 | 0x80,
                sxHeight=5 * PX if family.endswith("Sans") else cap * PX, sCapHeight=cap * PX)
    fb.setupPost()
    gasp = newTable("gasp")
    gasp.version = 1
    gasp.gaspRange = {0xFFFF: 0}   # never smooth or grid-fit: the outlines already sit on pixels
    fb.font["gasp"] = gasp
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    fb.save(path)


def preview(path):
    from PIL import Image, ImageDraw
    scale = 4
    lines = [("SANS", SANS, 7, 1), ("DISPLAY", DISPLAY, 11, 2)]
    img = Image.new("RGB", (1400, 560), (14, 20, 30))
    y = 8
    for label, glyphs, cap, spacing in lines:
        x = 8
        for ch, rows in glyphs.items():
            w = len(rows[0])
            if x + (w + spacing) * scale > 1390:
                x = 8
                y += (cap + 4) * scale
            for r, row in enumerate(rows):
                for c, p in enumerate(row):
                    if p == '#':
                        ImageDraw.Draw(img).rectangle(
                            [x + c * scale, y + r * scale, x + (c + 1) * scale - 1, y + (r + 1) * scale - 1],
                            fill=(236, 226, 200) if label == "SANS" else (238, 184, 64))
            x += (w + spacing + 1) * scale
        y += (cap + 6) * scale
    img.save(path)


